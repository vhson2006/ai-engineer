import { ApiProperty } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsString,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import {
  IMAGE_ASPECT_RATIOS,
  IMAGE_GENERATION_MAX_COUNT,
  IMAGE_PROMPT_MAX_LENGTH,
  type ImageAspectRatio,
} from '../ai/image.events';

/*
 * Media library of a site (ADR 0034): images for article covers and bodies. The admin's BROWSER
 * optimizes each image before uploading it (re-encoded as WebP, or JPEG where the browser can't
 * encode WebP; EXIF and GPS dropped; up to MEDIA_WIDTHS wide), then PUTs every size straight to
 * the PUBLIC bucket with presigned URLs (ADR 0014): the bytes never reach our servers.
 * Objects: `media/<siteId>/<mediaId>/<width>.<ext>`, served by the CDN, never changed (a new
 * image is a new id), so they can be cached forever.
 */

/** What the browser uploads: never SVG (it would run as our CDN's origin), never GIF/PNG originals. */
export const MEDIA_CONTENT_TYPES = ['image/webp', 'image/jpeg'] as const;
export type MediaContentType = (typeof MEDIA_CONTENT_TYPES)[number];
export const MEDIA_EXTENSIONS: Record<MediaContentType, string> = {
  'image/webp': 'webp',
  'image/jpeg': 'jpg',
};

/** The sizes the browser makes (no larger than the original): phone, laptop, full width. */
export const MEDIA_WIDTHS = [640, 1280, 1920] as const;
export const MEDIA_MAX_WIDTH = 1920;
/** Taller than wide is fine (portraits), but not a banner 20 times taller. */
export const MEDIA_MAX_HEIGHT = 4800;
/** Per size, after optimization (a 1920px WebP is ~200-600 KB). */
export const MEDIA_MAX_BYTES = 3 * 1024 * 1024;

export class MediaVariantDto {
  @ApiProperty({ example: 1280, maximum: MEDIA_MAX_WIDTH })
  @IsInt()
  @Min(1)
  @Max(MEDIA_MAX_WIDTH)
  width: number;

  @ApiProperty({ example: 853, maximum: MEDIA_MAX_HEIGHT })
  @IsInt()
  @Min(1)
  @Max(MEDIA_MAX_HEIGHT)
  height: number;

  @ApiProperty({ example: 182_311, description: 'Exact size in bytes', maximum: MEDIA_MAX_BYTES })
  @IsInt()
  @Min(1)
  @Max(MEDIA_MAX_BYTES)
  size: number;
}

/** POST /content/sites/:siteId/media: declare an optimized image and its sizes. */
export class CreateMediaUploadDto {
  @ApiProperty({ example: 'shop-front.jpg', maxLength: 200, description: 'Shown in the library' })
  @IsString()
  @IsNotEmpty()
  @MaxLength(200)
  filename: string;

  @ApiProperty({ enum: MEDIA_CONTENT_TYPES })
  @IsIn(MEDIA_CONTENT_TYPES)
  contentType: MediaContentType;

  @ApiProperty({ type: [MediaVariantDto], description: 'One per size, distinct widths' })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(MEDIA_WIDTHS.length)
  @ValidateNested({ each: true })
  @Type(() => MediaVariantDto)
  variants: MediaVariantDto[];
}

export interface MediaVariant {
  width: number;
  height: number;
  size: number;
  url: string;
}

/** An image as a page uses it: the largest size in `url`, every size in `srcset`. */
export interface MediaImage {
  id: string;
  url: string;
  width: number;
  height: number;
  /** `<url> 640w, <url> 1280w, …` for <img srcset>. */
  srcset: string;
}

/** failed: an AI generation that produced no image (ADR 0037). */
export type MediaStatus = 'pending' | 'ready' | 'failed';
/** upload: optimized in the admin's browser (ADR 0034); ai: generated by ai-service (ADR 0037). */
export type MediaSource = 'upload' | 'ai';

export interface MediaResponse extends MediaImage {
  siteId: string;
  filename: string;
  contentType: MediaContentType;
  status: MediaStatus;
  source: MediaSource;
  /** source ai: the description it was generated from. */
  prompt: string | null;
  /** status failed: why (a TranslationFailure-like reason). */
  error: string | null;
  variants: MediaVariant[];
  createdBy: string;
  createdAt: string;
}

/** Answer to POST …/media: PUT each size to its URL with exactly its headers, then POST …/complete. */
export interface MediaUploadResponse {
  media: MediaResponse;
  uploads: {
    width: number;
    method: 'PUT';
    url: string;
    headers: Record<string, string>;
    expiresAt: string;
  }[];
}

/** POST /content/sites/:siteId/media/generate: images from a description (ADR 0037). */
export class GenerateMediaDto {
  @ApiProperty({
    example: 'A bright laundromat with washing machines, flat illustration',
    maxLength: IMAGE_PROMPT_MAX_LENGTH,
  })
  @IsString()
  @IsNotEmpty()
  @MaxLength(IMAGE_PROMPT_MAX_LENGTH)
  prompt: string;

  @ApiProperty({ enum: IMAGE_ASPECT_RATIOS, example: '16:9' })
  @IsIn(IMAGE_ASPECT_RATIOS)
  aspectRatio: ImageAspectRatio;

  @ApiProperty({
    minimum: 1,
    maximum: IMAGE_GENERATION_MAX_COUNT,
    example: 2,
    description: 'How many options',
  })
  @IsInt()
  @Min(1)
  @Max(IMAGE_GENERATION_MAX_COUNT)
  count: number;
}

/** Answer to POST …/media/generate (202): the pending images; poll GET …/media/generations/:jobId. */
export interface MediaGenerationResponse {
  jobId: string;
  /** pending until ai-service answers; completed may hold fewer images than asked (some failed). */
  status: 'pending' | 'completed' | 'failed';
  media: MediaResponse[];
  /** Images this site may still generate this calendar month (UTC). */
  remaining: number;
}
